/*
 * Build `flux-pond.html`: the whole toy in one file, no imports, no origin.
 *
 * Several ways of opening this project cannot fetch `src/*.js`. `file://`
 * refuses module imports outright, and a preview pane that injects the markup
 * into a sandboxed origin -- a WebView, an iframe with a srcdoc -- has the same
 * trouble with no base URL to resolve against. Both paint the CSS panels over a
 * black canvas and never start the simulation, which looks like a broken toy
 * rather than a blocked request. An inline script needs no origin at all.
 *
 * `index.html` and `src/` stay the source of truth: this reads the page, bundles
 * the modules with esbuild (already on this host; nothing is downloaded), and
 * swaps the module tag for the bundle. `tests/app.test.mjs` rebuilds and
 * compares, so the generated file cannot drift from what it was built from.
 *
 *   node tools/build-standalone.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadOptional } from './optional-deps.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = 'flux-pond.html';
const SCRIPT_TAG = '<script type="module" src="src/main.js"></script>';

/*
 * The page's own comment tells the reader to start a server, which would be
 * wrong about the file this build emits. Both comments are matched exactly, so
 * editing the one in index.html fails the build loudly instead of leaving a
 * generated file describing itself incorrectly.
 */
const SOURCE_NOTE = `<!--
  Single page, no build step, no external assets. \`src/main.js\` is an ES module
  loaded over http://, which is why \`python3 serve.py\` is required rather than
  opening this file directly (file:// blocks module imports).
-->`;
const STANDALONE_NOTE = `<!--
  Single file: the modules are inlined below, so this opens from disk, from a
  sandboxed preview pane, or from any static server without requesting anything
  else. Generated from index.html -- see the comment above this one.
-->`;

const banner =
  'Generated by tools/build-standalone.mjs from index.html + src/*.js.\n' +
  'Edit those and re-run the build; nothing here is hand-written.';

function build() {
  const esbuild = loadOptional('esbuild');
  if (esbuild === null) {
    throw new Error('esbuild is not available on this host');
  }
  const result = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: ['src/main.js'],
    bundle: true,
    // A classic IIFE rather than a module: the whole point is to survive
    // contexts where module scripts cannot fetch anything.
    format: 'iife',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    write: false
  });
  const js = result.outputFiles[0].text;
  // An inline script ends at the first `</script>` it sees, wherever that is.
  return js.replaceAll('</script', '<\\/script');
}

export function renderStandalone() {
  const page = readFileSync(path.join(root, 'index.html'), 'utf8');
  for (const marker of [SCRIPT_TAG, SOURCE_NOTE]) {
    if (!page.includes(marker)) {
      throw new Error(`index.html no longer contains ${marker.slice(0, 46)}..., which this build replaces`);
    }
  }
  const bundle = build();
  return page
    .replace('<!doctype html>', `<!doctype html>\n<!-- ${banner} -->`)
    .replace(SOURCE_NOTE, STANDALONE_NOTE)
    .replace(SCRIPT_TAG, `<script>${bundle}</script>`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = renderStandalone();
  writeFileSync(path.join(root, OUTPUT), html);
  console.log(`${OUTPUT}: ${(html.length / 1024).toFixed(0)} KB`);
}
