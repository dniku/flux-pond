/*
 * Build `index.html`: the whole toy in one file, no imports, no origin.
 *
 * Several ways of opening this project cannot fetch `src/*.js`. `file://`
 * refuses module imports outright, and a preview pane that injects the markup
 * into a sandboxed origin -- a WebView, an iframe with a srcdoc -- has the same
 * trouble with no base URL to resolve against. Both paint the CSS panels over a
 * black canvas and never start the simulation, which looks like a broken toy
 * rather than a blocked request. An inline script needs no origin at all.
 *
 * So the page at the root of this repo -- the one to open -- is generated here,
 * from `src/page.html` and a bundle of `src/*.js`. That is the point: there is
 * one entry point and it works everywhere, rather than a page that works over a
 * server plus a second page that works anywhere. `tests/app.test.mjs` rebuilds
 * and compares bytes, so the generated file cannot drift from its sources.
 *
 *   node tools/build-standalone.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadOptional } from './optional-deps.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = 'src/page.html';
const OUTPUT = 'index.html';
// Read from the project root, not from src/: it is the specifier the emitted
// page would need if it loaded a module at all, which is the tag this replaces.
const SCRIPT_TAG = '<script type="module" src="src/main.js"></script>';

/*
 * The template's comment points at the build, which would be wrong about the
 * file the build emits. Both comments are matched exactly, so editing the one in
 * src/page.html fails the build loudly rather than leaving a generated file that
 * describes itself incorrectly.
 */
const SOURCE_NOTE = '<!--\n  The markup, not the page. Everything in this file is hand-written; the\n  `index.html` at the root is generated from it plus a bundle of `src/*.js`, so\n  that one file opens anywhere. Edit this and run `node tools/build-standalone.mjs`.\n-->';
const STANDALONE_NOTE = '<!--\n  Generated from src/page.html + src/*.js by tools/build-standalone.mjs. One\n  file, nothing fetched: it opens from disk, from a sandboxed preview pane, or\n  from any static server. To change it, edit src/ and re-run that build.\n-->';

const banner =
  'Generated by tools/build-standalone.mjs from src/page.html + src/*.js.\n' +
  'Edit those and re-run the build; nothing here is hand-written.';

function bundle() {
  const esbuild = loadOptional('esbuild');
  if (esbuild === null) {
    throw new Error('esbuild is not available on this host');
  }
  const result = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: ['src/main.js'],
    bundle: true,
    // A classic IIFE rather than a module: the whole point is to survive
    // contexts where module scripts cannot fetch anything.
    format: 'iife',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    write: false
  });
  const js = result.outputFiles[0].text;
  // An inline script ends at the first `</script>` it sees, wherever that is.
  return js.replaceAll('</script', '<\\/script');
}

export function renderStandalone() {
  const page = readFileSync(path.join(root, TEMPLATE), 'utf8');
  for (const marker of [SCRIPT_TAG, SOURCE_NOTE]) {
    if (!page.includes(marker)) {
      throw new Error(`${TEMPLATE} no longer contains ${marker.slice(0, 46)}..., which this build replaces`);
    }
  }
  return page
    .replace('<!doctype html>', `<!doctype html>\n<!-- ${banner} -->`)
    .replace(SOURCE_NOTE, STANDALONE_NOTE)
    .replace(SCRIPT_TAG, `<script>${bundle()}</script>`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = renderStandalone();
  writeFileSync(path.join(root, OUTPUT), html);
  console.log(`${OUTPUT}: ${(html.length / 1024).toFixed(0)} KB`);
}
